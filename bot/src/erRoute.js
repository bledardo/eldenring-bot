// Pre-compute map of duplicate boss names (names appearing more than once)
const _dupMap = new Map();
for (let i = 0; i < route.length; i++) {
  const entry = route[i];
  if (!_dupMap.has(entry.name)) {
    _dupMap.set(entry.name, []);
  }
  _dupMap.get(entry.name).push({
    name: entry.name,
    zone: entry.zone,
    level: entry.level,
    routeIndex: i,
  });
}
// Remove entries that only appear once (not duplicates)
for (const [name, entries] of _dupMap) {
  if (entries.length <= 1) _dupMap.delete(name);
}

/**
 * Returns an array of {name, zone, level, routeIndex} for bosses that appear
 * multiple times in the route, or null for unique bosses.
 * @param {string} bossName
 * @returns {Array|null}
 */
function getDuplicateZones(bossName) {
  return _dupMap.get(bossName) || null;
}

function getDuplicateBossNames() {
  return Array.from(_dupMap.keys());
}

// Export route as array (Array.isArray compatible) with helpers attached
route.getDuplicateZones = getDuplicateZones;
route.getDuplicateBossNames = getDuplicateBossNames;
module.exports = route;
